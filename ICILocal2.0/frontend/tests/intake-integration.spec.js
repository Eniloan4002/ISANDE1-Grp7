import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

// Opt in only against a disposable database: creates applications, people and setup records.
test('Pauline intake and requirements UI persists through confirmation and allocation',async({page})=>{
  test.skip(!process.env.ICI_LIVE_API||!process.env.ICI_TEST_USERNAME||!process.env.ICI_TEST_PASSWORD,'Requires a dedicated disposable backend and administrator.');
  test.setTimeout(120000);
  page.setDefaultTimeout(15000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  await page.route('https://fonts.gstatic.com/**',route=>route.abort());
  await page.goto('/enrollment/intake');
  await page.getByLabel('Username',{exact:true}).fill(process.env.ICI_TEST_USERNAME);
  await page.getByLabel('Password',{exact:true}).fill(process.env.ICI_TEST_PASSWORD);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Applicant Intake Form',exact:true})).toBeVisible();
  const bootstrapToken=await page.evaluate(()=>sessionStorage.getItem('ici_access_token'));
  const adminHeaders={Authorization:`Bearer ${bootstrapToken}`};
  const options=await (await page.request.get('/api/admin/accounts/reference-data',{headers:adminHeaders})).json();
  const registrar=`demo_journey_${Date.now()}`,registrarPassword='PrivateRegistrarJourney2026';
  const provisioned=await page.request.post('/api/admin/users',{headers:adminHeaders,data:{username:registrar,fullName:'Registrar Demo Journey',email:`${registrar}@example.invalid`,password:registrarPassword,grants:[{role:'ROLE_REGISTRAR',campusId:options.campuses[0].id}]}});
  expect(provisioned.status()).toBe(201);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();await expect(page.getByRole('heading',{name:'Staff sign in',exact:true})).toBeVisible();await page.goto('/enrollment/intake');
  await page.getByLabel('Username',{exact:true}).fill(registrar);await page.getByLabel('Password',{exact:true}).fill(registrarPassword);await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Applicant Intake Form',exact:true})).toBeVisible();
  const token=await page.evaluate(()=>sessionStorage.getItem('ici_access_token'));
  const headers={Authorization:`Bearer ${token}`};
  const suffix=Date.now();
  const yearResponse=await page.request.post('/api/setup/academic-years',{headers,data:{label:`UI-${suffix}`,startsOn:'2026-06-01',endsOn:'2027-05-31'}});
  expect(yearResponse.status()).toBe(201);const year=await yearResponse.json();
  const termResponse=await page.request.post('/api/setup/terms',{headers,data:{academicYearId:year.id,code:'S1',name:'Browser semester',startsOn:'2026-06-01',endsOn:'2026-12-31'}});
  expect(termResponse.status()).toBe(201);const term=await termResponse.json();
  const ref=await (await page.request.get('/api/intake/reference-data',{headers})).json();
  const campus=ref.campuses[0],program=ref.programs.find(item=>item.code==='STEM');
  await page.reload();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'Applicant Intake Form'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/integrated-intake-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  const first=`Browser${randomUUID().replace(/[^a-z]/g,'')}`;
  await page.getByLabel('First name',{exact:false}).fill(first);
  await page.getByLabel('Last name',{exact:false}).fill('Integration');
  await page.getByLabel('Date of birth',{exact:false}).fill('2009-03-09');
  await page.getByLabel('Applicant category',{exact:false}).selectOption('new');
  await page.getByLabel('Preferred campus',{exact:false}).selectOption(String(campus.id));
  await page.getByLabel('Academic term',{exact:false}).selectOption(String(term.id));
  await page.getByLabel(/^Program/).selectOption('SHS');
  await page.getByLabel(/^Track/).selectOption('ACADEMIC');
  await page.getByLabel('Strand / specialization',{exact:false}).selectOption('STEM');
  await page.getByLabel('Grade level',{exact:false}).fill('11');
  await page.getByLabel('Voucher classification',{exact:false}).selectOption('QVR');
  await page.getByLabel('Residential district').fill('Tibanga');
  await page.getByLabel('Transportation route').fill('North');
  await page.getByLabel('Full name',{exact:true}).fill('Integration Guardian');
  await page.getByRole('combobox',{name:'Relationship',exact:true}).selectOption('mother');
  const created=page.waitForResponse(response=>response.url().endsWith('/api/intake/applications')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Add applicant to queue'}).click();
  const createdResponse=await created;expect(createdResponse.status()).toBe(201);const applicant=await createdResponse.json();
  await expect(page.getByRole('heading',{name:`${first} Integration`,exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText(/Integration Guardian \(Mother/)).toBeVisible();
  await page.getByRole('button',{name:'Review and pre-enlist'}).click();
  await expect(page.getByText('Pre-enlisted',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Open requirements',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Requirements Checklist'})).toBeVisible();
  await page.getByRole('button',{name:'Contact details for follow-up'}).click();
  await expect(page.getByText('Integration Guardian',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close contact details'}).click();
  for(const code of ['COMPLETION','FORM137','GOOD_MORAL','PSA']){
    await page.getByLabel(`Status: ${code}`,{exact:true}).selectOption('submitted');
    await page.getByLabel(`Verification notes: ${code}`,{exact:true}).fill('Original inspected during integration test.');
    const saved=page.waitForResponse(response=>response.url().endsWith(`/requirements/${code}`)&&response.request().method()==='PUT');
    await page.getByRole('button',{name:`Save ${code}`,exact:true}).click();expect((await saved).status()).toBe(200);
    await expect(page.getByLabel(`Status: ${code}`,{exact:true})).toHaveValue('submitted');
  }
  await page.reload();await expect(page.getByLabel('Status: PSA',{exact:true})).toHaveValue('submitted');
  await expect(page.getByLabel('Verification notes: PSA',{exact:true})).toHaveValue('Original inspected during integration test.');
  await page.screenshot({path:'test-results/integrated-requirements-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/integrated-requirements-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('link',{name:'Continue to attendance'}).click();
  await page.getByLabel('Attendance date',{exact:true}).fill('2026-06-01');
  await page.getByLabel('Attendance status',{exact:true}).selectOption('present');
  await page.getByRole('button',{name:'Save attendance'}).click();
  await expect(page.getByRole('button',{name:'Confirm enrollment',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Confirm enrollment',exact:true}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect(page.getByText('Enrollment confirmed',{exact:true})).toBeVisible();
  const sectionResponse=await page.request.post('/api/sections',{headers,data:{campusId:campus.id,termId:term.id,programId:program.id,name:`Integrated-${suffix}`,gradeLevel:'11',capacity:1,room:'204'}});
  expect(sectionResponse.status()).toBe(201);
  await page.goto(`/enrollment/enrolled?applicationId=${applicant.id}`);
  await page.getByRole('button',{name:'Assign to this section'}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect(page.getByRole('button',{name:'Currently assigned'})).toBeDisabled();
  await page.reload();await expect(page.getByRole('button',{name:'Currently assigned'})).toBeDisabled();
  await expect(page.locator('.section-card')).toContainText('1 / 1');
  const final=await (await page.request.get(`/api/intake/applications/${applicant.id}`,{headers})).json();
  expect(final.status).toBe('enrolled');expect(final.workflow.enrollment.sectionId).toBeTruthy();
  await page.screenshot({path:'test-results/integrated-allocation-desktop.png',fullPage:true});
  expect(errors).toEqual([]);
});
